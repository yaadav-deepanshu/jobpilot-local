class CompanyPortalsManager:
    """Manager for the 100 big companies job portals"""

    def __init__(self, config: Optional[dict] = None):
        self.config = config or {}
        self.portals = self._load_portals()

    def _load_portals(self) -> List[Dict[str, Any]]:
        """Load company portals from config or default to BIG_COMPANY_PORTALS"""
        cfg_portals = self.config.get("company_portals")
        if cfg_portals and isinstance(cfg_portals, list) and len(cfg_portals) >= 10:
            return cfg_portals
        return BIG_COMPANY_PORTALS

    def count(self) -> int:
        """Return total count of company portals"""
        return len(self.portals)

    def get_categories(self) -> List[str]:
        """Return distinct categories sorted alphabetically"""
        cats = sorted(list({p.get("category", "General") for p in self.portals}))
        return cats

    def get_portals(
        self,
        category: Optional[str] = None,
        search: Optional[str] = None,
        ats_type: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """Filter portals by category, search term, or ATS type"""
        results = []
        c_filter = category.strip().lower() if category else None
        s_filter = search.strip().lower() if search else None
        ats_filter = ats_type.strip().lower() if ats_type else None

        for p in self.portals:
            if c_filter and c_filter not in p.get("category", "").lower():
                continue
            if ats_filter and ats_filter not in p.get("ats_type", "").lower():
                continue
            if s_filter:
                match_name = s_filter in p.get("name", "").lower()
                match_desc = s_filter in p.get("description", "").lower()
                match_id = s_filter in p.get("id", "").lower()
                match_loc = any(s_filter in loc.lower() for loc in p.get("locations", []))
                if not (match_name or match_desc or match_id or match_loc):
                    continue
            results.append(p)
        return results

    def get_portal_by_id(self, portal_id: str) -> Optional[Dict[str, Any]]:
        """Find a single portal by ID"""
        for p in self.portals:
            if p.get("id") == portal_id:
                return p
        return None

    def get_portal(self, portal_id: str) -> Optional[Dict[str, Any]]:
        """Convenience alias for get_portal_by_id"""
        return self.get_portal_by_id(portal_id)

    def build_search_url(
        self, portal_id: str, role: str = "DevOps Engineer", location: str = "Bengaluru"
    ) -> str:
        """Construct a tailored search URL for a company portal based on role and location"""
        portal = self.get_portal_by_id(portal_id)
        if not portal:
            return ""

        default_search = portal.get("search_url")
        if default_search and "DevOps" in default_search:
            # If the portal already has a rich pre-configured search query
            return default_search

        base = portal.get("portal_url", "")
        role_enc = urllib.parse.quote_plus(role)
        loc_enc = urllib.parse.quote_plus(location)
        return f"{base}?q={role_enc}&location={loc_enc}"

    def get_stats(self) -> Dict[str, Any]:
        """Return aggregate summary stats of portals"""
        by_category: Dict[str, int] = {}
        for p in self.portals:
            cat = p.get("category", "Other")
            by_category[cat] = by_category.get(cat, 0) + 1

        return {
            "total_companies": len(self.portals),
            "by_category": by_category,
            "categories": self.get_categories(),
        }
